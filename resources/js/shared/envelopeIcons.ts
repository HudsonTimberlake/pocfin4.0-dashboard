const isKey = (k: string | null | undefined): k is EnvelopeIconKey =>
  !!k && k in ENVELOPE_ICONS;

/** The key the name suggests; a wallet when nothing matches. */
export function iconKeyFor(name: string): EnvelopeIconKey {
  return RULES.find(([re]) => re.test(name))?.[1] ?? "wallet";
}

/** The envelope's icon: the one chosen (`icon`), else the one its name suggests. */
export function envelopeIcon(name: string, icon?: string | null): Icon {
  return ENVELOPE_ICONS[isKey(icon) ? icon : iconKeyFor(name)].Icon;
}

