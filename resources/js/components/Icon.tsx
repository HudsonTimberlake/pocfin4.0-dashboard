export type IconName = keyof typeof GLYPHS;

/** `stroke` is kept from the hand-drawn set: 2.2 and above draws Phosphor's bold weight. */
export default function Icon({ name, size = 20, stroke = 1.9, className }: { name: IconName; size?: number; stroke?: number; className?: string }) {
    const Glyph = GLYPHS[name];
    return <Glyph size={size} weight={stroke >= 2.2 ? 'bold' : 'regular'} aria-hidden="true" className={className} />;
}
